const dynamicErrorTranslations = [
  [/^可使用次數必須是 1 到 (\d+) 之間的整數$/, (match) => `Usable count must be an integer between 1 and ${match[1]}`],
  [/^文件大小不能超過 ([\d.]+)MB$/, (match) => `File size cannot exceed ${match[1]} MB`],
  [/^消息過大，最大 ([\d.]+)KB$/, (match) => `Message is too large. Maximum size: ${match[1]} KB`],
  [/^Telegram API 請求失敗：(\d+)$/, (match) => `Telegram API request failed: ${match[1]}`],
  [/^Telegram 文件下載失敗：(\d+)$/, (match) => `Telegram file download failed: ${match[1]}`],
  [/^演示接口未實現：(\w+) (.+)$/, (match) => `Demo endpoint not implemented: ${match[1]} ${match[2]}`]
];

export function localizeServerError(message) {
  const fixed = fixedErrorTranslations.get(message);
  if (fixed) return fixed;
  for (const [pattern, translate] of dynamicErrorTranslations) {
    const match = message.match(pattern);
    if (match) return translate(match);
  }
  return message;
}
